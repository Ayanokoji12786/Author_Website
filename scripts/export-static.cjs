#!/usr/bin/env node
/* Generate the standalone site from the same React markup as the Next.js app.
 * TypeScript is already a project dependency; no second bundler is needed.
 */
const fs = require("node:fs");
const path = require("node:path");
const ts = require("typescript");
const React = require("react");
const { renderToStaticMarkup } = require("react-dom/server");
const root = path.resolve(__dirname, "..");
const originals = {
  ".ts": require.extensions[".ts"],
  ".tsx": require.extensions[".tsx"],
};
for (const ext of [".ts", ".tsx"]) {
  require.extensions[ext] = (module, filename) => {
    const output = ts.transpileModule(fs.readFileSync(filename, "utf8"), {
      fileName: filename,
      compilerOptions: {
        module: ts.ModuleKind.CommonJS,
        jsx: ts.JsxEmit.ReactJSX,
        target: ts.ScriptTarget.ES2020,
        esModuleInterop: true,
      },
    });
    module._compile(output.outputText, filename);
  };
}
const Experience =
  require("../components/experience/LiteraryExperience.tsx").default;
const { book } = require("../lib/book-content.ts");
const Facts = require("../components/experience/BookFacts.tsx").default;
const { introBootstrap } = require("../lib/intro-bootstrap.ts");
const {
  site,
  sitePages,
  pageUrl,
  serializeSchema,
  crawlerRules,
  sitemapUrls,
} = require("../lib/site-seo.ts");
const escape = (text) =>
  String(text).replace(
    /[&<>"']/g,
    (char) =>
      ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[
        char
      ],
  );
function renderPage(page, content) {
  const { title, description } = sitePages[page];
  const home = page === "home";
  return `<!DOCTYPE html>
<!-- Generated by npm run build:static. Edit shared components/content/styles instead. -->
<html lang="en"><head>
<meta charset="UTF-8" /><meta name="viewport" content="width=device-width, initial-scale=1" />
${home ? `<script>${introBootstrap}</script>` : ""}
<title>${escape(title)}</title><meta name="description" content="${escape(description)}" />
<meta name="robots" content="index, follow" />
<link rel="canonical" href="${escape(pageUrl(page))}" />
<link rel="icon" href="/public/favicon.png" type="image/png" />
<link rel="preload" href="/public/fonts/cormorant-garamond-latin-wght-normal.woff2" as="font" type="font/woff2" crossorigin />
<link rel="preload" href="/public/fonts/inter-latin-wght-normal.woff2" as="font" type="font/woff2" crossorigin />
<link rel="stylesheet" href="/public/experience.css" />
${home ? "" : '<link rel="stylesheet" href="/public/book-facts.css" />'}
<meta property="og:type" content="website" /><meta property="og:title" content="${escape(title)}" />
<meta property="og:description" content="${escape(description)}" /><meta property="og:url" content="${escape(pageUrl(page))}" />
<meta property="og:site_name" content="${escape(site.name)}" />
<meta property="og:image" content="${escape(site.image)}" /><meta property="og:image:alt" content="Cover of ${escape(book.title)}" />
<meta name="twitter:card" content="summary_large_image" /><meta name="twitter:title" content="${escape(title)}" />
<meta name="twitter:description" content="${escape(description)}" /><meta name="twitter:image" content="${escape(site.image)}" />
<script type="application/ld+json">${serializeSchema(page)}</script>
${home ? '<script src="/public/experience.js" defer></script><script src="/public/book-journey.js" defer></script>' : ""}
</head><body>${content}</body></html>
`;
}
fs.writeFileSync(
  path.join(root, "index.html"),
  renderPage(
    "home",
    renderToStaticMarkup(
      React.createElement(Experience, { assetBase: "public" }),
    ),
  ),
);
fs.mkdirSync(path.join(root, "book-facts"), { recursive: true });
fs.writeFileSync(
  path.join(root, "book-facts/index.html"),
  renderPage(
    "facts",
    renderToStaticMarkup(React.createElement(Facts, { assetBase: "/public" })),
  ),
);
fs.writeFileSync(
  path.join(root, "robots.txt"),
  "# Generated from lib/site-seo.ts by npm run build:static.\n" +
    crawlerRules
      .map(
        ({ userAgent, allow }) => `User-agent: ${userAgent}\nAllow: ${allow}\n`,
      )
      .join("\n") +
    `\nSitemap: ${site.url}sitemap.xml\n`,
);
fs.writeFileSync(
  path.join(root, "sitemap.xml"),
  '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
    sitemapUrls
      .map((url) => `  <url><loc>${escape(url)}</loc></url>`)
      .join("\n") +
    "\n</urlset>\n",
);
for (const ext of [".ts", ".tsx"]) {
  if (originals[ext]) require.extensions[ext] = originals[ext];
  else delete require.extensions[ext];
}
console.log(
  "Generated the homepage, book facts, robots.txt and sitemap.xml from shared sources.",
);
